export function getLang(): Lang {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem("mega_mart_lang") === "ur" ? "ur" : "en";
}

export function setLang(lang: Lang): void {
  window.localStorage.setItem("mega_mart_lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
  window.dispatchEvent(new Event("mega-mart-lang"));
}

export function t(key: string): string {
  const lang = getLang();
  return STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}

/** Re-renders when the language changes. */
export function useLang(): Lang {
  const [lang, setLangState] = useState<Lang>(getLang());
  useEffect(() => {
    const handler = () => setLangState(getLang());
    window.addEventListener("mega-mart-lang", handler);
    return () => window.removeEventListener("mega-mart-lang", handler);
  }, []);
  return lang;
}

/** Applies the saved language (and RTL) to the document. */
export function useApplyLang(): void {
  useEffect(() => {
    const lang = getLang();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
  }, []);
}
